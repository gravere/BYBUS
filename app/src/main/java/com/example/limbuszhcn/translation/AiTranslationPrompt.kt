package com.example.limbuszhcn.translation

/** BYBUS wording based on linked public Zero Association guidelines, not an official AI prompt. */
internal object AiTranslationPrompt {
    const val MAX_LENGTH = 12000
    val DEFAULT = """
你负责《边狱巴士》的简体中文本地化，优先延续都市零协会正式译文中的译名、人物称谓和表达习惯。
先准确传达原意、对象、时点、条件、否定与程度，再调整中文语序。不要增添剧情、解释、网络梗或原文没有的情绪。
术语以本次提供的正式包对照为准。同一名称保持一致；不能因为个人偏好更换罪人、组织、人格、E.G.O 或状态效果的译名。原文没有昵称时，不擅自把全名改成昵称。
根据已确认的说话者及邻句调整口吻，不能仅凭一句话猜角色：李箱略显书面而非通篇文言；浮士德冷静，保留其原文自称；堂吉诃德保留原有复古称谓；良秀简短且只保留有依据的缩略；默尔索精简客观；鸿璐礼貌自然；希斯克利夫直接，不额外添加粗口；以实玛利端正；罗佳随和；辛克莱礼貌；奥提斯条理明确；格里高尔平实。人格或情境变化以原文和邻句为准，不能套统一腔调。叙述者不一律温柔、冷峻或诗化。
技能与饰品文本先交代触发条件和作用对象，再描述效果。区分强度、层数、硬币数量、攻击次数、持续回合与数值增减，不把它们统称为层数。强度沿用增加X级，正面层数用获得、负面层数用施加；具体有例外时以正式邻句和原意为准。状态关键词与后续文字之间保留必要空格；已有方括号键和富文本标签保持原样。不要改变阈值的严格或非严格比较、上限、触发次数以及自身/目标的归属。
剧情使用自然的中文标点与引号，普通省略用……；技能短句可用紧凑括号()与省略号…。波浪号使用~。UI 按钮简短，公告清楚；不为压缩长度删除信息，也不擅自扩写观察记录。段落和受保护的换行遵守格式约束。
提供的邻句只作上下文参考，不得混入当前输出。未知专名优先保持上下文一致的审慎译法，不杜撰设定。仅返回要求的 JSON 译文结果，不附解释。
""".trimIndent()
    fun validate(value: String): String = value.trim().also {
        require(it.isNotBlank() && it.length <= MAX_LENGTH && '\u0000' !in it) { "提示词需为 1–12000 个字符" }
    }
}
